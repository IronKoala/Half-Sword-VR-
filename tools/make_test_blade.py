"""Writes a simple leaf-shaped test blade as a Wavefront OBJ for the HalfSwordCustomWeapon test.

The geometry is generated here from numbers (no third-party model). Axes are Unreal's:
centimetres, the blade runs along +Z from the guard (Z = 0), its edges point along +-X and its
flats face +-Y. Triangles are written counter-clockwise when seen from outside (the usual OBJ
convention); the mod reverses them for Unreal.

Usage: python tools/make_test_blade.py [out.obj] [length_cm]
"""
import math
import sys

out = sys.argv[1] if len(sys.argv) > 1 else "mod/HalfSwordCustomWeapon/test_blade.obj"
length = float(sys.argv[2]) if len(sys.argv) > 2 else 90.0

RINGS = 24
pos = []   # (x, y, z)
uvs = []
tris = []  # (a, b, c) indices into pos, counter-clockwise from outside


def half_width(t):
    # t = 0 at the guard, 1 at the point. Leaf: 2.4 cm at the guard, widest (3.6 cm) at 60 %, point at 1.
    if t < 0.6:
        return 2.4 + 1.2 * math.sin(t / 0.6 * math.pi / 2)
    return 3.6 * math.cos((t - 0.6) / 0.4 * math.pi / 2) ** 0.8


def half_thick(t):
    return 0.45 * (1.0 - 0.6 * t)


# Each ring: 4 points of a diamond cross-section: +X edge, +Y flat ridge, -X edge, -Y flat ridge.
ring_start = []
for i in range(RINGS):
    t = i / RINGS
    z = t * length
    w, h = half_width(t), half_thick(t)
    ring_start.append(len(pos))
    for (x, y) in ((w, 0), (0, h), (-w, 0), (0, -h)):
        pos.append((x, y, z))
        uvs.append((0.5 + x / 8.0, t))
tip = len(pos)
pos.append((0.0, 0.0, length))
uvs.append((0.5, 1.0))

# Sides. Going round +X -> +Y -> -X -> -Y is counter-clockwise seen from +Z, so for an outward
# face between ring i (lower) and i+1 (upper): (lo_j, lo_k, hi_k) and (lo_j, hi_k, hi_j).
for i in range(RINGS - 1):
    lo, hi = ring_start[i], ring_start[i + 1]
    for j in range(4):
        k = (j + 1) % 4
        tris.append((lo + j, lo + k, hi + k))
        tris.append((lo + j, hi + k, hi + j))
last = ring_start[-1]
for j in range(4):
    k = (j + 1) % 4
    tris.append((last + j, last + k, tip))
# Base cap (faces -Z): clockwise seen from +Z.
b = ring_start[0]
tris.append((b + 0, b + 2, b + 1))
tris.append((b + 0, b + 3, b + 2))

with open(out, "w", newline="\n") as f:
    f.write("# HalfSwordCustomWeapon test blade, generated by tools/make_test_blade.py\n")
    f.write(f"# Unreal axes, centimetres, blade along +Z from the guard, length {length:g} cm\n")
    for p in pos:
        f.write("v %.4f %.4f %.4f\n" % p)
    for uv in uvs:
        f.write("vt %.4f %.4f\n" % uv)
    for (a, bb, c) in tris:
        f.write(f"f {a+1}/{a+1} {bb+1}/{bb+1} {c+1}/{c+1}\n")
print(f"wrote {out}: {len(pos)} vertices, {len(tris)} triangles")
